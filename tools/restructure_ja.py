def svc(sid):
    for s in d["services"]:
        if s["id"] == sid:
            return s
    raise SystemExit("service not found: " + sid)


def item(s, title):
    for it in s["items"]:
        if it["title"] == title:
            return it
    raise SystemExit("item not found: " + title)


